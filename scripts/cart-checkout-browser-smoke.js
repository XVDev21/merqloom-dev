async page => {
  const base = 'http://127.0.0.1:18000'
  const screens = 'docs/verification/screens'
  const check = (value, message) => { if (!value) throw new Error(message) }
  const focus = async locator => check(await locator.evaluate(el => {
    const css = getComputedStyle(el)
    return document.activeElement === el && css.outlineStyle !== 'none' && parseFloat(css.outlineWidth) >= 2
  }), 'Expected visible focus')
  const reflow = async width => check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Horizontal overflow at ' + width)
  const shotWidths = async (name, ready) => {
    for (const width of [360, 390, 768, 1280, 1440]) {
      await page.setViewportSize({width, height:900})
      await ready.waitFor()
      await reflow(width)
      check(await page.evaluate(() => matchMedia('(prefers-reduced-motion: reduce)').matches), 'Reduced motion unavailable')
      await page.screenshot({path:`${screens}/mq103-${name}-${width}.png`,fullPage:true})
    }
  }
  await page.context().clearCookies()
  await page.emulateMedia({reducedMotion:'reduce'})
  await page.setViewportSize({width:390,height:900})
  await page.goto(base + '/store/desk-tray?variant=variant_missing')
  await page.getByText(/This finish is unavailable/).waitFor()
  check(await page.getByRole('button', {name:/Add .* to cart/}).count() === 0, 'Invalid finish can be added')
  await page.getByRole('link', {name:'Natural'}).click()
  const addNatural = page.getByRole('button', {name:'Add Natural to cart'})
  await page.getByLabel('Quantity').focus()
  await page.keyboard.press('Tab')
  await focus(addNatural)
  await page.keyboard.press('Enter')
  await page.waitForURL(url => url.pathname === '/store/cart')
  await page.getByText('Natural', {exact:true}).waitFor()
  await page.reload()
  await page.getByText('Natural', {exact:true}).waitFor()
  await page.goto(base + '/store/desk-tray')
  await page.getByRole('link', {name:'Walnut'}).click()
  await page.getByRole('button', {name:'Add Walnut to cart'}).click()
  await page.waitForURL(url => url.pathname === '/store/cart')
  await page.getByText('Walnut', {exact:true}).waitFor()
  const naturalLine = page.getByRole('listitem').filter({hasText:'Natural'})
  await naturalLine.getByLabel('Quantity').fill('2')
  const update = naturalLine.getByRole('button', {name:'Update'})
  await naturalLine.getByLabel('Quantity').focus()
  await page.keyboard.press('Tab')
  await focus(update)
  await page.keyboard.press('Enter')
  await page.getByText(/PHP\s1,420\.00/).first().waitFor()
  await shotWidths('cart', page.getByRole('heading', {name:'Your cart'}))
  await page.getByRole('link', {name:'Continue to simulated checkout'}).click()
  await shotWidths('checkout', page.getByRole('heading', {name:'Simulated checkout'}))
  await page.getByRole('button', {name:'Review simulated order'}).click()
  await page.getByText('Enter a valid email address.').waitFor()
  check(await page.getByLabel('Email').evaluate(el => document.activeElement === el), 'First invalid field did not receive focus')
  await focus(page.getByLabel('Email'))
  await shotWidths('validation', page.getByText('Please correct the marked fields.'))
  await page.getByLabel('Email').fill('shopper@example.test')
  await page.getByLabel('First name').fill('Demo')
  await page.getByLabel('Last name').fill('Shopper')
  await page.getByLabel('Street address').fill('1 Sample Street')
  await page.getByLabel('City or municipality').fill('Makati')
  await page.getByLabel('Philippine postal code').fill('12')
  await page.getByRole('button', {name:'Review simulated order'}).click()
  await page.getByText('Enter a four-digit postal code.').waitFor()
  check(await page.getByLabel('Email').inputValue() === 'shopper@example.test', 'Valid fields were lost during correction')
  await page.getByLabel('Philippine postal code').fill('1200')
  await page.getByRole('button', {name:'Review simulated order'}).click()
  await page.getByRole('heading', {name:'Review your demo order'}).waitFor()
  await page.getByText(/PHP\s1,430\.00/).waitFor()
  check(await page.getByText(/Simulated payment and simulated shipping/).count() > 0, 'Missing pre-submit disclosure')
  const submit = page.getByRole('button', {name:'Place simulated order — payment and shipping simulated'})
  await page.getByRole('link', {name:'Edit contact and address'}).focus()
  await page.keyboard.press('Tab')
  await focus(submit)
  await page.evaluate(() => {
    sessionStorage.removeItem('mq103-pending-observed')
    const button = [...document.querySelectorAll('button')].find(el => el.textContent.includes('Place simulated order'))
    const observer = new MutationObserver(() => {
      if (button.disabled && button.textContent.includes('Placing simulated order')) sessionStorage.setItem('mq103-pending-observed', 'yes')
    })
    observer.observe(button, { attributes: true, childList: true, characterData: true, subtree: true })
  })
  await page.route('**/store/checkout/action', async route => {
    await new Promise(resolve => setTimeout(resolve, 800))
    await route.continue()
  })
  await page.keyboard.press('Enter')
  await page.waitForURL(base + '/store/confirmation')
  check(await page.evaluate(() => sessionStorage.getItem('mq103-pending-observed')) === 'yes', 'Pending feedback was not shown during submit')
  await page.unroute('**/store/checkout/action')
  await page.getByRole('heading', {name:'Simulated order placed'}).waitFor()
  await page.getByText(/Payment and shipping are simulated/).waitFor()
  await page.reload()
  await page.getByRole('heading', {name:'Simulated order placed'}).waitFor()
  await shotWidths('confirmation', page.getByRole('heading', {name:'Simulated order placed'}))
  const isolated = await page.context().browser().newContext()
  try {
    const other = await isolated.newPage()
    await other.goto(base + '/store/cart')
    await other.getByRole('heading', {name:'Your cart is empty'}).waitFor()
    await other.goto(base + '/store/confirmation')
    await other.getByRole('heading', {name:'No confirmed order in this session'}).waitFor()
  } finally { await isolated.close() }
  return 'Both finishes, persistence, native totals, keyboard focus, field validation, simulated disclosures, confirmation refresh, session separation, reduced motion and reflow passed at five widths'
}
