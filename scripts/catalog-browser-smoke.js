async page => {
  const base = "http://127.0.0.1:18000"
  const screens = "docs/verification/screens"
  const check = (value, message) => { if (!value) throw new Error(message) }
  const catalog = () => page.getByRole("heading", { name: "Demo catalog" })
  const search = () => page.getByRole("searchbox", { name: "Search products" })
  const collection = () => page.getByLabel("Collection")
  const focused = locator => locator.evaluate(el => {
    const style = getComputedStyle(el)
    return document.activeElement === el && style.outlineStyle !== "none" && parseFloat(style.outlineWidth) >= 2
  })
  const reflow = () => page.evaluate(() => document.documentElement.scrollWidth === innerWidth)
  const alt = (pattern) => page.getByRole("img", { name: pattern })
  const loaded = locator => locator.evaluate(image => image.complete && image.naturalWidth > 0 && image.width > 0)
  const waitImage = async locator => {
    await locator.waitFor()
    await locator.evaluate(image => image.decode())
    check(await loaded(locator), "Missing product visual")
  }

  await page.emulateMedia({ reducedMotion: "reduce" })
  await page.goto(base)
  await page.getByRole("link", { name: "Explore the demo catalog" }).first().click()
  await catalog().waitFor()
  await page.getByRole("link", { name: "Organizer pouch", exact: true }).waitFor()
  // Search plus collection, using keyboard on the text field and the submit control.
  await page.keyboard.press("Tab")
  await page.getByRole("link", { name: "Skip to content" }).focus()
  check(await focused(page.getByRole("link", { name: "Skip to content" })), "Missing visible skip-link focus")
  await page.keyboard.press("Enter")
  await page.keyboard.press("Tab")
  check(await focused(search()), "Search must receive visible keyboard focus")
  await page.keyboard.type("desk tray")
  await page.keyboard.press("Tab")
  check(await focused(collection()), "Collection must receive visible keyboard focus")
  await page.keyboard.press("d")
  await page.keyboard.press("Tab")
  check(await focused(page.getByRole("button", { name: "Apply filters" })), "Filter submit must receive focus")
  await page.keyboard.press("Enter")
  await page.waitForURL(url => url.searchParams.get("q") === "desk tray" &&
    url.searchParams.get("collection") === "desk-organization")
  await page.getByText("1 product", { exact: true }).waitFor()
  check(await page.getByRole("link", { name: "Organizer pouch", exact: true }).count() === 0, "Wrong collection membership")
  const filterUrl = page.url()

  const tray = page.getByRole("link", { name: "Desk tray", exact: true })
  await tray.click()
  await page.waitForURL(url => url.pathname === "/store/desk-tray" && !url.searchParams.has("variant"))
  const naturalUrl = page.url()
  await page.getByRole("heading", { name: "Desk tray" }).waitFor()
  await page.getByRole("link", { name: "Natural" }).and(page.locator("[aria-current=true]")).waitFor()
  await page.getByText(/PHP\s450\.00/).waitFor()
  await page.getByText("240 × 160 × 25 mm", { exact: true }).waitFor()
  const walnut = page.getByRole("link", { name: "Walnut" })
  // Tab from Natural to Walnut, then select without a pointer.
  await page.getByRole("link", { name: "Natural" }).focus()
  await page.keyboard.press("Tab")
  check(await focused(walnut), "Walnut must receive visible keyboard focus")
  await page.keyboard.press("Enter")
  await page.waitForURL(url => url.searchParams.has("variant"))
  const walnutUrl = page.url()
  await walnut.and(page.locator("[aria-current=true]")).waitFor()
  await page.getByText(/PHP\s520\.00/).waitFor()
  await page.getByText(/available in the demo/).waitFor()
  await waitImage(alt(/Walnut-finish desk tray/))
  await page.reload()
  await page.getByText(/PHP\s520\.00/).waitFor()
  await page.goBack()
  check(page.url() === naturalUrl, "Browser Back lost the original variant URL")
  await page.getByText(/PHP\s450\.00/).waitFor()
  await page.getByRole("link", { name: "Back to catalog" }).click()
  await page.waitForURL(filterUrl)
  await page.getByText("1 product", { exact: true }).waitFor()
  check(await search().inputValue() === "desk tray" && await collection().inputValue() === "desk-organization",
    "Filter URL did not restore form state")

  await search().fill("unmatched-fixture")
  await page.getByRole("button", { name: "Apply filters" }).click()
  await page.getByRole("heading", { name: "No products match" }).waitFor()
  await page.getByRole("link", { name: "Browse all products" }).click()
  await page.getByText("2 products", { exact: true }).waitFor()
  await page.getByRole("link", { name: "Organizer pouch", exact: true }).click()
  await page.getByText("Out of stock", { exact: true }).waitFor()
  await page.getByText("Fictional supplier preview", { exact: true }).waitFor()
  await page.getByText(/PHP\s320\.00/).waitFor()
  await waitImage(alt(/canvas organizer pouch/))
  await page.goto(base + "/store/desk-tray?variant=variant_missing")
  await page.getByText(/This finish is unavailable/).waitFor()
  check(await page.locator("article figure img").count() === 0, "Invalid finish showed a variant illustration")
  check(await page.getByText(/PHP\s(?:450|520)\.00/).count() === 0, "Invalid variant showed a different variant's price")
  await page.getByRole("link", { name: "Natural" }).click()
  await page.getByText(/PHP\s450\.00/).waitFor()
  await waitImage(alt(/pale birch desk tray/))
  await page.goto(base + "/store/missing-product")
  await page.getByRole("heading", { name: "Product not found" }).waitFor()
  await page.getByRole("link", { name: "Browse the catalog" }).click()
  await catalog().waitFor()
  await page.getByRole("link", { name: "Merqloom Studio" }).click()
  await page.getByRole("heading", { name: "Commerce, connected" }).waitFor()

  for (const width of [360, 390, 768, 1280, 1440]) {
    await page.setViewportSize({ width, height: 900 })
    await page.goto(base + "/store")
    await catalog().waitFor()
    await waitImage(alt(/pale birch desk tray/))
    await waitImage(alt(/canvas organizer pouch/))
    check(await reflow(), "Catalog overflow at " + width)
    check(await alt(/pale birch desk tray/).evaluate(el => matchMedia("(prefers-reduced-motion: reduce)").matches &&
      getComputedStyle(el).transitionDuration === "0s"), "Catalog image animated with reduced motion")
    await page.screenshot({ path: screens + "/mq102-catalog-" + width + ".png", fullPage: true })
    await page.goto(walnutUrl)
    await page.getByText(/PHP\s520\.00/).waitFor()
    await waitImage(alt(/Walnut-finish desk tray/))
    check(await reflow(), "Detail overflow at " + width)
    await page.screenshot({ path: screens + "/mq102-variant-" + width + ".png", fullPage: true })
  }

  await page.setViewportSize({ width: 390, height: 900 })
  await page.goto(base + "/store/organizer-pouch")
  await page.getByText("Out of stock", { exact: true }).waitFor()
  await waitImage(alt(/canvas organizer pouch/))
  await page.screenshot({ path: screens + "/mq102-pouch-390.png", fullPage: true })

  return "Store round trip, keyboard search and variant, URL restoration, invalid and unavailable states, alt text and reflow at five widths passed"
}
